class Exercise {
  final String id;
  final String name;
  final String muscle;
  final String machine;
  final bool timed; // esercizio a tempo (plank, cardio…)
  final bool custom; // creato dal coach

  const Exercise(this.id, this.name, this.muscle, this.machine,
      {this.timed = false, this.custom = false});

  /// Video standard: ricerca YouTube dell'esecuzione corretta.
  String get standardVideoUrl =>
      'https://www.youtube.com/results?search_query=${Uri.encodeComponent('$name esecuzione corretta')}';

  Map<String, dynamic> toMap() =>
      {'name': name, 'muscle': muscle, 'machine': machine, 'timed': timed};

  factory Exercise.fromMap(String id, Map<String, dynamic> m) => Exercise(
        id,
        (m['name'] as String?) ?? 'Esercizio',
        (m['muscle'] as String?) ?? 'Altro',
        (m['machine'] as String?) ?? 'Altro',
        timed: m['timed'] == true,
        custom: true,
      );
}

